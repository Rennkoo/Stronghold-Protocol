import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {PlaySession} from './unity-play-server.mjs';
const recording=JSON.parse(readFileSync(new URL('../public/dev/recordings/normal-m01.json',import.meta.url)));
const placements=recording.field.units.map(u=>({id:u.id,row:u.y,col:u.x}));
const a=new PlaySession();let view=a.start(placements);assert.equal(view.gt,0);
assert.throws(()=>new PlaySession().start(placements.map(p=>({...p,row:0,col:0}))));
assert.throws(()=>new PlaySession().command({action:'step'}));
for(let i=0;i<100;i++)view=a.command({action:'step'});
assert.ok(view.gt>=9.9);assert.ok(view.states.some(s=>s.id>7));
const before=view.gt;a.command({action:'state'});assert.equal(a.battle.time,before);
for(const u of a.battle.allyUnits)if(u.skill?.manual)assert.equal(u.skill.rule,'NEVER');
const manual=a.battle.allyUnits.find(u=>u.skill?.manual&&!u.skill.noSkill&&u.alive&&u.deployed);
assert.ok(manual);manual.skill.addCharge(1);
const activations=manual.skill.activations;a.command({action:'skill',id:manual.uid});assert.ok(manual.skill.activations>activations);
while(!a.battle.finished)view=a.command({action:'step'});
assert.equal(view.finished,true);assert.ok(view.total>0);assert.equal(a.battle.errors.length,0);
const b=new PlaySession();view=b.start(placements);assert.equal(view.gt,0);
console.log(JSON.stringify({passed:true,realSimulation:true,total:a.battle.total,killed:a.battle.killed,manualSkill:manual.name,reset:true}));
